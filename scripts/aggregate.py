"""Aggregate projects/*/status.md into one planner-readable summary.md.

Usage:  python scripts/aggregate.py [--root STATUS_ROOT]
Root: --root, else the STATUS_ROOT environment variable, else the folder above scripts/.
Idempotent: output depends only on the status files, and summary.md is
rewritten only when its content changes.

Requires: PyYAML
"""
import argparse
import datetime as dt
import os
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("ERROR: PyYAML missing. Run: pip install pyyaml")

ROOT_DEFAULT = Path(__file__).resolve().parent.parent

REQUIRED = [
    "project", "last_updated", "status", "progress", "next_actions", "blockers",
    "effort_estimate", "priority", "last_session", "notes_for_planner",
]
STATUSES = ["blocked", "active", "paused", "done"]  # also the sort order
EFFORTS = {"low", "medium", "high"}
MAX_BODY_WORDS = 200


def expand(value):
    """Expand ${VAR} references from os.environ (repeated for nested refs)."""
    for _ in range(5):
        new = re.sub(r"\$\{(\w+)\}", lambda m: os.environ.get(m.group(1), ""), value)
        if new == value:
            break
        value = new
    return value


def load_env(path):
    """Minimal .env loader. Existing env vars win."""
    if not path.is_file():
        print(f"note: {path} not found, using defaults")
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = (s.strip() for s in line.split("=", 1))
        os.environ.setdefault(key, value.strip('"').strip("'"))


def env_path(key, default):
    # Values may hold unexpanded ${VAR} text (e.g. set as Windows env vars).
    return Path(expand(os.environ.get(key, str(default))))


def as_text(value):
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    return "" if value is None else str(value)


def parse(path):
    """Return (frontmatter dict, body str). Raises ValueError on bad format."""
    text = path.read_text(encoding="utf-8-sig")
    m = re.match(r"\A---\s*\n(.*?)\n---\s*(?:\n(.*))?\Z", text, re.S)
    if not m:
        raise ValueError("no YAML frontmatter between '---' lines")
    try:
        meta = yaml.safe_load(m.group(1))
    except yaml.YAMLError as e:
        raise ValueError(f"bad YAML: {str(e).splitlines()[0]}")
    if not isinstance(meta, dict):
        raise ValueError("frontmatter is not a key/value mapping")
    return meta, (m.group(2) or "").strip()


def validate(meta, body, folder):
    """Return a list of schema warnings (empty if clean)."""
    w = [f"missing '{k}'" for k in REQUIRED if k not in meta]
    w += [f"unknown key '{k}'" for k in meta if k not in REQUIRED]
    if meta.get("project") is not None and str(meta["project"]) != folder:
        w.append(f"project '{meta['project']}' != folder '{folder}'")
    if "status" in meta and meta["status"] not in STATUSES:
        w.append(f"status '{meta['status']}' not in {'|'.join(STATUSES)}")
    if "effort_estimate" in meta and meta["effort_estimate"] not in EFFORTS:
        w.append(f"effort_estimate '{meta['effort_estimate']}' not low|medium|high")
    p = meta.get("priority")
    if "priority" in meta and not (isinstance(p, int) and 1 <= p <= 5):
        w.append(f"priority '{p}' not an integer 1-5")
    for key in ("next_actions", "blockers"):
        if key in meta and not isinstance(meta[key], list):
            w.append(f"'{key}' is not a list")
    if meta.get("status") == "blocked" and not meta.get("blockers"):
        w.append("status is blocked but blockers is empty")
    words = len(body.split())
    if words > MAX_BODY_WORDS:
        w.append(f"body has {words} words (max {MAX_BODY_WORDS})")
    return w


def cell(value):
    if isinstance(value, list):
        value = "; ".join(as_text(v) for v in value)
    return as_text(value).replace("|", "/").replace("\n", " ").strip() or "-"


def sort_key(meta):
    status = meta.get("status")
    prio = meta.get("priority")
    return (
        STATUSES.index(status) if status in STATUSES else len(STATUSES),
        prio if isinstance(prio, int) else 99,
        str(meta.get("project", "")),
    )


def build_summary(rows, issues):
    as_of = max((as_text(m.get("last_updated")) for m in rows), default="n/a")
    counts = {s: sum(1 for m in rows if m.get("status") == s) for s in STATUSES}
    out = [
        "# Project status summary",
        "",
        "Generated by scripts/aggregate.py. Do not edit by hand.",
        f"Latest update: {as_of} | Projects: {len(rows)} | "
        + " | ".join(f"{s}: {n}" for s, n in counts.items()),
        "Priority 1 = highest. Sorted by status (blocked first), then priority.",
        "",
    ]
    if rows:
        out += [
            "| P | Project | Status | Progress | Effort | Last session | Next actions | Blockers | Note |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for m in sorted(rows, key=sort_key):
            out.append("| " + " | ".join(cell(m.get(k)) for k in (
                "priority", "project", "status", "progress", "effort_estimate",
                "last_session", "next_actions", "blockers", "notes_for_planner",
            )) + " |")
    else:
        out.append("_No projects yet. Add projects/<project>/status.md (see schema.md)._")
    if issues:
        out += ["", "## Validation issues", ""]
        out += [f"- `{name}`: {'; '.join(msgs)}" for name, msgs in sorted(issues.items())]
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description="Aggregate projects/*/status.md into summary.md.")
    ap.add_argument("--root", help="status root (folder that holds projects/)")
    args = ap.parse_args()
    if args.root:
        os.environ["STATUS_ROOT"] = args.root
    load_env(env_path("STATUS_ROOT", ROOT_DEFAULT) / ".env")
    root = env_path("STATUS_ROOT", ROOT_DEFAULT)
    projects_dir = env_path("STATUS_PROJECTS_DIR", root / "projects")
    summary_file = env_path("STATUS_SUMMARY_FILE", root / "summary.md")

    if not projects_dir.is_dir():
        print(f"ERROR: projects dir not found: {projects_dir}")
        return 1

    rows, issues, failed = [], {}, 0
    folders = sorted(p for p in projects_dir.iterdir() if p.is_dir())
    for folder in folders:
        path = folder / "status.md"
        name = folder.name
        if not path.is_file():
            issues[name] = ["no status.md"]
            print(f"  skip  {name}: no status.md")
            continue
        try:
            meta, body = parse(path)
        except (ValueError, OSError, UnicodeDecodeError) as e:
            issues[name] = [f"unreadable: {e}"]
            failed += 1
            print(f"  FAIL  {name}: {e}")
            continue
        warnings = validate(meta, body, name)
        meta.setdefault("project", name)
        if warnings:
            issues[name] = warnings
        rows.append(meta)
        print(f"  {'warn' if warnings else 'ok':5} {name}" + (f": {'; '.join(warnings)}" if warnings else ""))

    summary = build_summary(rows, issues)
    old = summary_file.read_text(encoding="utf-8") if summary_file.is_file() else None
    if summary == old:
        print(f"summary unchanged: {summary_file}")
    else:
        try:
            summary_file.write_text(summary, encoding="utf-8", newline="\n")
        except OSError as e:
            print(f"ERROR: cannot write {summary_file}: {e}")
            return 1
        print(f"wrote {summary_file}")
    print(f"{len(folders)} folders, {len(rows)} aggregated, {len(issues)} with issues, {failed} failed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
